/**
 * Static Killer Sudoku learning content (Russian UI copy).
 * Progress ids are opaque strings — keep lesson ids stable across releases.
 */

/** Digit keypad quiz attached to a lesson (optional). */
export interface LessonInteractive {
	/** Question shown above the digit row. */
	prompt: string
	/**
	 * Optional multiple-choice labels; when omitted the UI shows digits 1–9.
	 * Correct answer is always validated via correctDigit.
	 */
	options?: readonly string[]
	/** Expected digit (1–9). */
	correctDigit: number
	/** Short confirmation after a correct tap. */
	successMessage: string
	/** Optional monospace / ASCII board sketch for the prompt. */
	boardVisual?: string
}

/** One unlock-free tutorial lesson. */
export interface Lesson {
	id: string
	title: string
	/** Body copy as separate paragraphs (RU). */
	body: readonly string[]
	interactive?: LessonInteractive
}

